import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawn } from 'node:child_process';

test('local import, worker spawning, and parallel batch leases', async () => {
  const workspace=path.resolve(process.cwd());
  const root=path.resolve(workspace,`.queue-test-${process.pid}`);
  assert.ok(root.startsWith(workspace+path.sep));
  await fs.mkdir(root,{recursive:true});
  const port=44000+(process.pid%1000);
  const child=spawn(process.execPath,[path.join(workspace,'server.mjs')],{cwd:workspace,env:{...process.env,EMOJI_QUEUE_ROOT:root,EMOJI_QUEUE_PORT:String(port)},stdio:'ignore'});
  const base=`http://127.0.0.1:${port}`;
  try {
    let token;
    for(let i=0;i<50;i++){try{token=(await fs.readFile(path.join(root,'.upload-queue','token.txt'),'utf8')).trim();const response=await fetch(base+'/api/status',{headers:{'X-Queue-Token':token}});if(response.ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
    assert.ok(token,'test server did not start');
    const headers={'X-Queue-Token':token};
    const landing=await fetch(base+'/').then(r=>r.text());
    const theme=await fetch(base+'/studio.css');
    const status=await fetch(base+'/api/status',{headers}).then(r=>r.json());
    assert.match(landing,/Parallel tabs<select id="workers">/);
    assert.match(landing,/\/studio\.css/);
    assert.equal(theme.headers.get('content-type'),'text/css; charset=utf-8');
    assert.match(await theme.text(),/backdrop-filter:blur/);
    assert.equal(status.protocolVersion,'0.4.0');
    assert.equal(status.studioVersion,'0.4.5');
    assert.equal(status.root,root);
    const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aQb8AAAAASUVORK5CYII=','base64');
    const imported=await fetch(base+'/api/import?pack=Sample&filename=test-icon.png',{method:'POST',headers,body:png});
    assert.equal(imported.status,200,await imported.text().catch(()=>''));
    const catalog=await fetch(base+'/api/catalog?folder=Sample&limit=10',{headers}).then(r=>r.json());
    assert.equal(catalog.total,1);assert.equal(catalog.items[0].title,'Test Icon');
    const edited=await fetch(base+'/api/edit',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({folder:'Sample',filename:'test-icon.png',title:'Edited Icon',description:'Edited description.',tags:'emoji; test; cute'})});
    assert.equal(edited.status,200);
    const after=await fetch(base+'/api/catalog?folder=Sample&limit=10',{headers}).then(r=>r.json());
    assert.equal(after.items[0].title,'Edited Icon');
    const start=await fetch(base+'/api/start',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({limit:0,folder:'Sample'})});
    assert.equal(start.status,400,'outdated or absent worker must block submission');
    const enable=await fetch(base+'/api/enable-pairing',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:'{}'});
    assert.equal(enable.status,200);
    const paired=await fetch(base+'/api/pair',{headers:{'X-Queue-Pair':'local-userscript'}}).then(r=>r.json());
    assert.equal(paired.token,token);
    const secondPair=await fetch(base+'/api/pair',{headers:{'X-Queue-Pair':'local-userscript'}});
    assert.equal(secondPair.status,403,'pairing token is one-use');
    await fetch(base+'/api/hello',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({version:'0.4.0',scriptVersion:'0.4.2',clientId:crypto.randomUUID()})});
    assert.equal((await fetch(base+'/api/status',{headers}).then(r=>r.json())).workerReady,false,'outdated tab cannot start uploads');
    const firstClientId=crypto.randomUUID();
    const hello=await fetch(base+'/api/hello',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({version:'0.4.0',scriptVersion:'0.4.5',heartbeat:true,clientId:firstClientId})}).then(r=>r.json());
    assert.ok(hello.session);
    const connected=await fetch(base+'/api/status',{headers}).then(r=>r.json());
    assert.equal(connected.workerTabs.find(w=>w.version==='0.4.5').connected,true);
    assert.equal(connected.readyWorkers,1);
    const idleTabs=await fetch(base+'/api/workers',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({workers:3})}).then(r=>r.json());
    assert.equal(idleTabs.spawnPending,2,'applying tab count while idle prepares missing workers');
    const idleSpawn=await fetch(base+'/api/hello',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({version:'0.4.0',scriptVersion:'0.4.5',heartbeat:true,clientId:firstClientId})}).then(r=>r.json());
    assert.equal(idleSpawn.spawn,2);
    const queued=await fetch(base+'/api/start',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({limit:0,folder:'Sample',workers:3})}).then(r=>r.json());
    assert.equal(queued.queued,1);
    const spawn=await fetch(base+'/api/hello',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({version:'0.4.0',scriptVersion:'0.4.5',heartbeat:true,clientId:firstClientId})}).then(r=>r.json());
    assert.equal(spawn.spawn,2,'the first worker opens two more tabs');
    const workerHeaders={...headers,'X-Worker-Session':hello.session};
    const batch=await fetch(base+'/api/next',{headers:workerHeaders}).then(r=>r.json());
    assert.equal(batch.batch.items.length,1);
    const result=await fetch(base+'/api/result',{method:'POST',headers:{...workerHeaders,'Content-Type':'application/json'},body:JSON.stringify({id:batch.batch.id,outcomes:[{status:'submitted'}]})});
    assert.equal(result.status,200);
    assert.ok((await fs.stat(path.join(root,'.uploaded-Sample','upload_manifest.csv'))).isFile());
    for(let i=0;i<23;i++)assert.equal((await fetch(base+`/api/import?pack=Parallel&filename=icon-${i}.png`,{method:'POST',headers,body:png})).status,200);
    const hellos=await Promise.all(Array.from({length:3},()=>fetch(base+'/api/hello',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({version:'0.4.0',scriptVersion:'0.4.5',heartbeat:true,clientId:crypto.randomUUID()})}).then(r=>r.json())));
    const multi=await fetch(base+'/api/start',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({limit:0,folder:'Parallel',workers:3})}).then(r=>r.json());
    assert.equal(multi.queued,23);
    const changed=await fetch(base+'/api/workers',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify({workers:10})}).then(r=>r.json());
    assert.equal(changed.workers,10);
    const leases=await Promise.all(hellos.map(h=>fetch(base+'/api/next',{headers:{...headers,'X-Worker-Session':h.session}}).then(r=>r.json())));
    assert.deepEqual(leases.map(x=>x.batch.items.length),[10,10,3]);
    assert.equal(new Set(leases.flatMap(x=>x.batch.items.map(i=>i.filename))).size,23);
    const repeat=await fetch(base+'/api/next',{headers:{...headers,'X-Worker-Session':hellos[0].session}}).then(r=>r.json());
    assert.equal(repeat.batch,null,'an active worker must not receive a second lease');
    const file=await fetch(base+`/api/file?batch=${leases[0].batch.id}&index=0`,{headers:{...headers,'X-Worker-Session':hellos[1].session}});
    assert.equal(file.status,404,'workers cannot read each others leases');
    for(const index of [2,0,1]){
      const lease=leases[index].batch;
      const response=await fetch(base+'/api/result',{method:'POST',headers:{...headers,'X-Worker-Session':hellos[index].session,'Content-Type':'application/json'},body:JSON.stringify({id:lease.id,outcomes:lease.items.map(()=>({status:'submitted'}))})});
      assert.equal(response.status,200);
    }
    const final=await fetch(base+'/api/status',{headers}).then(r=>r.json());
    assert.equal(final.done,23);assert.equal(final.leased,0);assert.equal(final.running,false);
    assert.ok((await fs.stat(path.join(root,'.uploaded-Parallel','upload_manifest.csv'))).isFile());
  } finally {
    child.kill();
    await new Promise(resolve=>child.once('exit',resolve));
    assert.ok(root.startsWith(workspace+path.sep));
    await fs.rm(root,{recursive:true,force:true});
  }
});
